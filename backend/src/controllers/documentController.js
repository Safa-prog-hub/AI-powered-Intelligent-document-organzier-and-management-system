/**
 * documentController.js — Orchestration logic (Phase 2)
 *
 * POST /api/documents/upload  → save the uploaded file + create a processing
 *                               job, then process the AI task in the background.
 * GET  /api/documents         → list / smart-search the user's documents.
 * GET  /api/documents/expiring→ documents expiring within 30 days (dashboard).
 * GET  /api/documents/:id     → single document.
 * DELETE /api/documents/:id   → remove document (+ its storage artifact).
 */

const fs = require('fs');
const path = require('path');
const Document = require('../models/Document');
const aiService = require('../services/aiService');
const { uploadDir } = require('../middleware/multerConfig');

const EXPIRY_WINDOW_DAYS = 30;

/** Best-effort cleanup of a temporary upload artifact. */
function safeUnlink(filePath) {
  return fs.promises.unlink(filePath).catch((err) => {
    console.warn(
      `[gateway] Could not remove temp file ${filePath}: ${err.message}`
    );
  });
}

/**
 * Process a document in the background.
 *
 * This function intentionally runs outside the HTTP response flow.
 * The upload endpoint can respond immediately while this work continues.
 */
async function processDocumentInBackground({
  documentId,
  file,
  userId,
  existingEmbeddings,
}) {
  try {
    console.log(
      `[gateway] Background processing started for document ${documentId}`
    );

    // ── Dispatch to the Python AI microservice ─────────────────────────────
    const aiResult = await aiService.processDocument(file, {
      existingEmbeddings,
    });

    // ── Map the AI response into the Document schema ───────────────────────
    const metadata = aiResult.metadata || {};

    await Document.findOneAndUpdate(
      {
        _id: documentId,
        userId,
      },
      {
        $set: {
          extractedText: aiResult.extractedText || '',
          tags: Array.isArray(aiResult.tags) ? aiResult.tags : [],
          embedding: aiResult.embedding || undefined,

          metadata: {
            documentCategory: metadata.documentCategory || 'Others',
            idNumber: metadata.idNumber ?? null,
            name: metadata.name ?? null,
            issueDate: metadata.issueDate || null,
            expiryDate: metadata.expiryDate || null,
            autoGeneratedFilename:
              metadata.autoGeneratedFilename || file.originalname,
          },

          processingStatus: 'completed',
          processingError: null,
        },
      }
    );

    console.log(
      `[gateway] Background processing completed for document ${documentId}`
    );
  } catch (err) {
    console.error(
      `[gateway] Background processing failed for document ${documentId}:`,
      err.message
    );

    try {
      await Document.findOneAndUpdate(
        {
          _id: documentId,
          userId,
        },
        {
          $set: {
            processingStatus: 'failed',
            processingError: err.message || 'Document processing failed',
          },
        }
      );
    } catch (updateError) {
      console.error(
        `[gateway] Could not update failed status for document ${documentId}:`,
        updateError.message
      );
    }
  }
}

